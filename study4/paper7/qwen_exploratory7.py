#!/usr/bin/env python3
"""qwen_exploratory7.py: an exploratory look at the Qwen3.6-27B clusters that were completed before its lane stopped.

Not part of the registered analysis (PREREGISTRATION_STUDY4.md): Qwen's registered tests are "not tested" because fewer
than 96 of its 128 clusters entered. This script takes the clusters that have all four configs (the first ones in the
fixed visit order: instance, then family and config), computes the cluster values of S4-H1 to S4-H6 exactly as the plan
defines them, and an exact sign-flip p for each (one-sided; two-sided for H6), with no adjustment. It supports no
confirmatory claim. It reads only results.csv and shares no code with analysis7.

    python3 paper7/qwen_exploratory7.py --base ../data/results7/study4 --latex <paper latex folder>
"""
import argparse
import collections
import csv
import os
from decimal import ROUND_HALF_UP, Decimal
from fractions import Fraction

CONFIGS = ("locks_s2text", "locks_instr", "locks_signals", "locks")
NAMES = {"H1": "Hone", "H2": "Htwo", "H3": "Hthree", "H4": "Hfour", "H5": "Hfive", "H6": "Hsix"}


def value(h, f):
    a, i, s, b = (f[c] for c in CONFIGS)
    return {"H1": a - b, "H2": (a + s) / 2 - (i + b) / 2, "H3": (a + i) / 2 - (s + b) / 2, "H4": a - i, "H5": a - s,
            "H6": (a - i) - (s - b)}[h]


def signflip(values):
    """Exact sign-flip distribution of the sum (values are multiples of 1/2): P(sum >= observed), P(sum <= observed)."""
    sc = [round(2 * v) for v in values]
    dist = collections.Counter({0: 1})
    for s in sc:
        nxt = collections.Counter()
        for k, c in dist.items():
            nxt[k + s] += c
            nxt[k - s] += c
        dist = nxt
    obs, total = sum(sc), 2 ** len(sc)
    return (sum(c for k, c in dist.items() if k >= obs) / total, sum(c for k, c in dist.items() if k <= obs) / total)


def pfmt(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--latex", required=True)
    a = ap.parse_args()
    by = collections.defaultdict(dict)
    with open(os.path.join(a.base, "n2-openrouter", "results.csv")) as f:
        for r in csv.DictReader(f):
            by[(r["family"], int(r["instance"]))][r["config"]] = int(r["fs_nonserializable"])
    full = {k: v for k, v in by.items() if all(c in v for c in CONFIGS)}
    words = {0: "zero", 1: "one", 2: "two", 3: "three", 4: "four"}
    insts = sorted({k[1] for k in full})
    M = {"SivXQwenClusters": str(len(full)), "SivXQwenFamilies": str(len({k[0] for k in full})),
         "SivXQwenInstances": words.get(len(insts), str(len(insts)))}
    for h, nm in NAMES.items():
        vals = [value(h, full[k]) for k in sorted(full)]
        ge, le = signflip(vals)
        p = min(1.0, 2 * min(ge, le)) if h == "H6" else ge
        mean = sum(Fraction(v).limit_denominator(2) for v in vals) / len(vals)  # exact; rounded half up
        M[f"SivXQwen{nm}Est"] = str((Decimal(mean.numerator) / Decimal(mean.denominator)).quantize(Decimal("0.01"), ROUND_HALF_UP))
        M[f"SivXQwen{nm}P"] = pfmt(p)
    out = os.path.join(a.latex, "study4_out", "study4_qwen_exploratory.tex")
    with open(out, "w") as f:
        f.write("% GENERATED by paper7/qwen_exploratory7.py (exploratory; not part of the registered analysis)\n")
        for k in sorted(M):
            f.write(f"\\newcommand{{\\{k}}}{{{M[k]}}}\n")
    print(f"{len(full)} complete Qwen clusters; wrote {out}")
    for k in sorted(M):
        print(" ", k, M[k])


if __name__ == "__main__":
    main()
